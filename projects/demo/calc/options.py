"""Порядок величины эффекта вариантов за плановый год. Входы брифа — [E…], остальное — допущения
команды (D…), записанные в реестр как hypothesis. Два сценария: основной и неблагоприятный.

  python projects/demo/calc/options.py
"""
MONTH_PROFIT = 500          # руб. за доп. оплаченный месяц номера [E015]
NEED_MONTHS = 12_000        # до цели 285 млн руб. [E025]
CONNECTED_AVG = 7_250       # средн. подключённых групп в плановом году: (6 500 + 8 000) / 2 [E005]
CONNECTED_END = 8_000       # без изменений на конец года [E005]
ACTIVE_SHARE_NC = 0.625     # доля активных без изменений [E021]
OWNERS_AVG = 900            # средн. подключённых владельцев: (800 + 1 000) / 2 [E006]
# Календарь (D22): разработка апрель–15 мая, тестирование до 31 мая, пилот с 1 июня на половине подходящих групп;
# сигнал до перебоя — на всех подходящих с 1 сентября; запуск группы — на всех новых группах с 1 декабря.
EFFECT_MONTHS = 4 + 3 * 0.5   # сигнал: 4 мес. на всех + 3 мес. пилота на половине = 5,5 «полных» месяца
LAUNCH_TREATED = 6 * 0.5 + 1  # запуск: месяцев набора новых групп с изменением — июнь–ноябрь половина, декабрь все

S = {  # допущения: основной / неблагоприятный
    "members":        (2.0, 1.6),   # D1 участников на группу (кроме организатора)
    "eligible":       (0.6, 0.45),  # D2 доля номеров, где помощь возможна: тариф с общим пакетом + право + согласие
    "episodes":       (3.0, 2.0),   # D3 перебоев из-за исчерпания доли на номер в год
    "preventable":    (0.45, 0.30), # E028 доля перебоев при свободном остатке (30–60 %)
    "acts_in_time":   (0.5, 0.35),  # D4 доля предупреждений, после которых организатор успевает выделить
    "months_saved":   (0.2, 0.1),   # D5 доп. оплаченных месяцев на предотвращённый перебой
    "warned_groups":  (0.4, 0.3),   # D6 доля подходящих групп, получающих предупреждение за месяц
    "router_stops":   (2.0, 1.0),   # D7 остановок номера роутера из-за неоплаты в год
    "router_saved":   (0.5, 0.25),  # D8 доп. оплаченных месяцев на предотвращённую остановку
    "router_acts":    (0.6, 0.4),   # D9 доля предупреждений, после которых владелец пополняет вовремя
    "created":        (6000, 5000), # D10 групп создаётся за год
    "uplift":         (0.07, 0.03), # D11 рост доли активированных за 14 дней от напоминаний и первого действия (45 % без изменений [E007])
    "stay":           (0.7, 0.5),   # D12 доля дополнительно активированных групп, которые остаются подключёнными и активными на конец года
}


def row(i):
    p = {k: v[i] for k, v in S.items()}
    half = EFFECT_MONTHS / 12
    # Вариант 3: сигнал организатору до перебоя
    numbers = CONNECTED_AVG * p["members"] * p["eligible"]
    prevented = numbers * p["episodes"] * p["preventable"] * p["acts_in_time"] * half
    v3_months = prevented * p["months_saved"]
    v3_active = CONNECTED_END * p["eligible"] * p["warned_groups"] * p["acts_in_time"] * (1 - ACTIVE_SHARE_NC)
    # Вариант 4: общий кабинет — те же случаи плюс неоплата: допускаем охват причин ×1,5 при той же доле действий
    v4_months = v3_months * 1.5
    v4_active = v3_active * 1.5
    # Вариант 5: владельцы роутеров
    v5_prevented = OWNERS_AVG * p["router_stops"] * p["router_acts"] * half
    v5_months = v5_prevented * p["router_saved"]
    # Вариант 6: запуск группы + сигнал до перебоя (запуск действует на новые группы, созданные с изменением)
    extra_groups = p["created"] / 12 * LAUNCH_TREATED * p["uplift"] * p["stay"]
    v6_active = v3_active + extra_groups
    v6_connected = extra_groups
    return dict(v6a=v6_active, v6c=v6_connected, numbers=numbers, prevented=prevented, v3=v3_months, v3a=v3_active, v4=v4_months, v4a=v4_active,
                v5=v5_months, v5p=v5_prevented)


def main():
    for i, name in enumerate(("основной", "неблагоприятный")):
        r = row(i)
        print(f"Сценарий: {name}")
        print(f"  подходящих номеров участников: {r['numbers']:,.0f}; предотвращённых перебоев за год: {r['prevented']:,.0f}".replace(",", " "))
        for key, label in (("v3", "В3 сигнал до перебоя"), ("v4", "В4 общий кабинет"), ("v5", "В5 роутеры владельцев")):
            m = r[key]
            print(f"  {label:24s}: {m:>6,.0f} доп. месяцев = {m * MONTH_PROFIT / 1e6:.2f} млн руб. "
                  f"({m / NEED_MONTHS:.1%} от нужных 12 000)".replace(",", " "))
        print(f"  прирост активных групп к концу года: В3 +{r['v3a']:.0f}, В4 +{r['v4a']:.0f}, В6 +{r['v6a']:.0f} (нужно +3 000 к «без изменений»)")
        print(f"  прирост подключённых групп от запуска (В6): +{r['v6c']:.0f} (нужно +4 000)")
        print()
    # Граница решения: какой эффект нужен, чтобы В3 закрыл 6 млн
    r = row(0)
    need_per_prevented = NEED_MONTHS / r["prevented"]
    print(f"Граница: чтобы В3 закрыл 6 млн руб. в плановом году, каждый предотвращённый перебой должен давать "
          f"{need_per_prevented:.1f} доп. оплаченных месяца (в основном сценарии допущено {S['months_saved'][0]}).")


if __name__ == "__main__":
    main()
